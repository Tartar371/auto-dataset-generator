def build_telegram_text(bundle: dict[str, Any]) -> str:
    day = bundle["date"]
    payloads = bundle["payloads"]
    fng = ((payloads.get("fear_greed") or {}).get("items") or [{}])[0]
    gecko = (payloads.get("coingecko") or {}).get("items") or []
    movers = sorted(
        [c for c in gecko if isinstance(c.get("change_24h_pct"), (int, float))],
        key=lambda c: abs(c["change_24h_pct"]),
        reverse=True,
    )[:5]
    mover_lines = [
        f"• {c.get('symbol')}: {_fmt_pct(c.get('change_24h_pct'))} @ {_fmt_money(c.get('price_usd'))}"
        for c in movers
    ] or ["• no market rows"]
    fx = (payloads.get("fx") or {}).get("rates") or {}
    return "\n".join(
        [
            f"Daily dataset {day} [{bundle['status']}]",
            f"Fear & Greed: {fng.get('classification')} ({fng.get('value')})",
            f"USD FX: {json.dumps(fx, separators=(',', ':'))}" if fx else "USD FX: n/a",
            "Top |24h| movers:",
            *mover_lines,
            f"OK: {', '.join(bundle['ok_collectors']) or 'none'}",
        ]
    )
