"""Markdown + HTML report builders and Telegram/Discord summaries."""

from __future__ import annotations

import html
import json
from typing import Any


def _fmt_money(value: Any) -> str:
    try:
        number = float(value)
    except (TypeError, ValueError):
        return "n/a"
    if number >= 1_000_000_000:
        return f"${number / 1_000_000_000:.2f}B"
    if number >= 1_000_000:
        return f"${number / 1_000_000:.2f}M"
    if number >= 1_000:
        return f"${number:,.0f}"
    return f"${number:,.4f}"


def _fmt_pct(value: Any) -> str:
    try:
        return f"{float(value):+.2f}%"
    except (TypeError, ValueError):
        return "n/a"


def flatten_market_rows(payloads: dict[str, Any]) -> list[dict[str, Any]]:
    gecko = payloads.get("coingecko") or {}
    return list(gecko.get("items") or [])


def build_markdown(bundle: dict[str, Any]) -> str:
    day = bundle["date"]
    payloads = bundle["payloads"]
    lines = [
        f"# Daily Market & Tech Intelligence — {day}",
        "",
        "Autogenerated from **public APIs only** (CoinGecko, Alternative.me, Frankfurter/ECB, DefiLlama, Hacker News, arXiv).",
        "This is research data, not financial advice.",
        "",
        f"- Status: **{bundle['status']}**",
        f"- Collectors OK: {', '.join(bundle['ok_collectors']) or 'none'}",
        f"- Collectors failed: {', '.join(f['collector'] for f in bundle['failed_collectors']) or 'none'}",
        "",
    ]

    fx = payloads.get("fx")
    if fx:
        rates = fx.get("rates") or {}
        pretty = ", ".join(f"{k}={v}" for k, v in rates.items())
        lines += [f"## FX (USD base, ECB via Frankfurter, {fx.get('date')})", "", pretty, ""]

    fng = payloads.get("fear_greed")
    if fng and fng.get("items"):
        today = fng["items"][0]
        lines += [
            "## Crypto Fear & Greed",
            "",
            f"{today.get('classification')} ({today.get('value')}/100)",
            "",
        ]

    gecko = payloads.get("coingecko")
    if gecko and gecko.get("items"):
        lines += [
            "## Top crypto by market cap",
            "",
            "| Rank | Symbol | Price | 24h | 7d | Market cap | Volume 24h |",
            "| ---: | --- | ---: | ---: | ---: | ---: | ---: |",
        ]
        for coin in gecko["items"][:15]:
            lines.append(
                f"| {coin.get('rank')} | {coin.get('symbol')} | {_fmt_money(coin.get('price_usd'))} "
                f"| {_fmt_pct(coin.get('change_24h_pct'))} | {_fmt_pct(coin.get('change_7d_pct'))} "
                f"| {_fmt_money(coin.get('market_cap_usd'))} | {_fmt_money(coin.get('volume_24h_usd'))} |"
            )
        lines.append("")

    llama = payloads.get("defillama")
    if llama and llama.get("items"):
        lines += ["## DefiLlama chain TVL (top 10)", "", "| Chain | TVL |", "| --- | ---: |"]
        for chain in llama["items"][:10]:
            lines.append(f"| {chain.get('name')} | {_fmt_money(chain.get('tvl_usd'))} |")
        lines.append("")

    hn = payloads.get("hackernews")
    if hn and hn.get("items"):
        lines += ["## Hacker News — top stories", ""]
        for story in hn["items"][:8]:
            title = story.get("title") or "(untitled)"
            url = story.get("url") or f"https://news.ycombinator.com/item?id={story.get('id')}"
            lines.append(f"- [{title}]({url}) — {story.get('score')} pts")
        lines.append("")

    arxiv = payloads.get("arxiv")
    if arxiv and arxiv.get("items"):
        lines += ["## Latest arXiv (cs.AI / cs.LG / q-fin.TR)", ""]
        for paper in arxiv["items"][:8]:
            lines.append(f"- [{paper.get('title')}]({paper.get('id')})")
        lines.append("")

    if bundle["failed_collectors"]:
        lines += ["## Collector errors", ""]
        for failure in bundle["failed_collectors"]:
            lines.append(f"- `{failure['collector']}`: {failure['error']}")
        lines.append("")

    lines += [
        "## License / attribution",
        "",
        "Code is MIT. Underlying data remains owned by the source APIs; include attribution if you redistribute.",
        "",
    ]
    return "\n".join(lines) + "\n"


def build_html(bundle: dict[str, Any], markdown: str) -> str:
    day = html.escape(bundle["date"])
    status = html.escape(str(bundle["status"]))
    body_rows = []
    gecko = (bundle.get("payloads") or {}).get("coingecko") or {}
    for coin in (gecko.get("items") or [])[:20]:
        body_rows.append(
            "<tr>"
            f"<td>{html.escape(str(coin.get('rank') or ''))}</td>"
            f"<td>{html.escape(str(coin.get('symbol') or ''))}</td>"
            f"<td>{html.escape(str(coin.get('name') or ''))}</td>"
            f"<td>{html.escape(_fmt_money(coin.get('price_usd')))}</td>"
            f"<td>{html.escape(_fmt_pct(coin.get('change_24h_pct')))}</td>"
            f"<td>{html.escape(_fmt_money(coin.get('market_cap_usd')))}</td>"
            "</tr>"
        )
